    HOURLY_RATE DECIMAL(8,2),
    BREAK_MINUTES INTEGER DEFAULT 0,
    NOTES VARCHAR(255),
    APPROVED_BY INTEGER,
    STATUS VARCHAR(20) DEFAULT 'ACTIVE',
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (ID)
);

CREATE INDEX IF NOT EXISTS IDX_TC_EMPLOYEE ON TIME_CLOCK (EMPLOYEE_ID);
CREATE INDEX IF NOT EXISTS IDX_TC_CLOCK_IN ON TIME_CLOCK (CLOCK_IN);
CREATE INDEX IF NOT EXISTS IDX_TC_STATUS ON TIME_CLOCK (STATUS);

