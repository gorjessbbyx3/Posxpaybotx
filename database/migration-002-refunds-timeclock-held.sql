-- 1. Refund Tracking Table
-- =============================================
CREATE TABLE IF NOT EXISTS REFUND (
    ID INTEGER NOT NULL AUTO_INCREMENT,
    TICKET_ID INTEGER NOT NULL,
    AMOUNT DECIMAL(12,2) NOT NULL,
    REFUND_TYPE VARCHAR(20) NOT NULL DEFAULT 'FULL',
    REASON VARCHAR(255),
    PAYMENT_METHOD VARCHAR(20),
    PROCESSED_BY VARCHAR(100),
    PROCESSED_BY_ID INTEGER,
    STATUS VARCHAR(20) DEFAULT 'COMPLETED',
    ORIGINAL_TRANSACTION_ID INTEGER,
    REFUND_TRANSACTION_ID INTEGER,
    NOTES TEXT,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (ID)
);

CREATE INDEX IF NOT EXISTS IDX_REFUND_TICKET ON REFUND (TICKET_ID);
CREATE INDEX IF NOT EXISTS IDX_REFUND_DATE ON REFUND (CREATED_AT);
CREATE INDEX IF NOT EXISTS IDX_REFUND_PROCESSED_BY ON REFUND (PROCESSED_BY_ID);

