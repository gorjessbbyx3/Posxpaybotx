-- 3. Time Clock / Labor Tracking
-- =============================================
CREATE TABLE IF NOT EXISTS TIME_CLOCK (
    ID INTEGER NOT NULL AUTO_INCREMENT,
    EMPLOYEE_ID INTEGER NOT NULL,
    EMPLOYEE_NAME VARCHAR(100),
    ROLE VARCHAR(50),
    CLOCK_IN TIMESTAMP NOT NULL,
    CLOCK_OUT TIMESTAMP,
